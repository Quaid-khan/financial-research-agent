"""Orchestrator script executing all 8 End-to-End Benchmark Challenges and rendering RESULTS.md summary report."""

import time
import logging
from pathlib import Path

from eval.challenges import (
    run_challenge_01,
    run_challenge_02,
    run_challenge_03,
    run_challenge_04,
    run_challenge_05,
    run_challenge_06,
    run_challenge_07,
    run_challenge_08,
)

logger = logging.getLogger("financial_agent.eval.benchmark_runner")


def run_all_challenges() -> list:
    """Execute all 8 benchmark challenges sequentially."""
    print("=== Running 8 End-to-End Financial Agent Benchmark Challenges ===")
    
    runners = [
        ("Challenge 1: Single-Company Filing Lookup", run_challenge_01),
        ("Challenge 2: Multi-Year Trend Analysis", run_challenge_02),
        ("Challenge 3: Transcript Guidance Extraction", run_challenge_03),
        ("Challenge 4: Cross-Source Conflict Resolution", run_challenge_04),
        ("Challenge 5: Multi-Company Benchmark Comparison", run_challenge_05),
        ("Challenge 6: Memory-Dependent Follow-Up", run_challenge_06),
        ("Challenge 7: Reasoning Under Ambiguity", run_challenge_07),
        ("Challenge 8: Capstone Report & Scorecard Evaluation", run_challenge_08),
    ]

    results = []
    for title, runner in runners:
        start_t = time.time()
        res = runner()
        elapsed = round(time.time() - start_t, 2)
        res["duration_sec"] = elapsed
        results.append(res)
        status = "PASSED [OK]" if res["passed"] else "FAILED [FAIL]"
        print(f"  * [{res['challenge_id'].upper()}] {title} -> {status} ({elapsed}s)")

    generate_results_md(results)
    return results


def generate_results_md(results: list) -> str:
    """Generate Markdown summary report in RESULTS.md."""
    passed_count = len([r for r in results if r["passed"]])
    total_count = len(results)
    pass_rate = (passed_count / total_count) * 100.0

    lines = [
        "# Benchmark Evaluation Results & Capstone Verification",
        "",
        f"**Benchmark Pass Rate**: `{pass_rate:.1f}% ({passed_count}/{total_count} Passed)` | **Date**: August 2026",
        "---",
        "",
        "## Executive Benchmark Summary",
        "This evaluation suite systematically validates the autonomous financial agent across 8 progressively difficult end-to-end research challenges testing Phases 1 through 6.",
        "",
        "## Challenge Results Matrix",
        "| Challenge ID | Challenge Title | Steps Taken | Execution Time | Pass/Fail Status |",
        "| :--- | :--- | :--- | :--- | :--- |"
    ]

    for r in results:
        status_str = "PASSED ✅" if r["passed"] else "FAILED ❌"
        lines.append(f"| `{r['challenge_id']}` | {r['title']} | {r['steps_taken']} steps | {r['duration_sec']}s | {status_str} |")

    lines.append("")
    lines.append("## Detailed Challenge Breakdown & Success Criteria")

    criteria_details = [
        ("challenge_01", "Single-Company Filing Lookup", "get_financial_statements / sec_edgar_search", "Extracted 10-K revenue disclosure ($158.0B)."),
        ("challenge_02", "Multi-Year Trend Analysis", "get_financial_statements (multi-year)", "Analyzed 3-year revenue growth trajectory across FY2022-FY2024."),
        ("challenge_03", "Transcript Guidance Extraction", "get_earnings_transcript", "Extracted executive NIM guidance and consumer credit metrics."),
        ("challenge_04", "Cross-Source Conflict Resolution", "ConflictDetector / SynthesisEngine", "Detected 12% revenue discrepancy and applied SEC 10-K priority rule."),
        ("challenge_05", "Multi-Company Benchmark Comparison", "get_financial_statements (JPM, BAC, AAPL)", "Benchmarked revenues across 3 distinct corporate entities."),
        ("challenge_06", "Memory-Dependent Follow-Up", "search_memory / recall_findings", "Retrieved pre-seeded long-term ChromaDB memory entry."),
        ("challenge_07", "Reasoning Under Ambiguity", "get_financial_statements (resolved entity)", "Resolved 'Chase' reference to JPMorgan Chase & Co. (JPM)."),
        ("challenge_08", "Capstone Report & Scorecard Evaluation", "Full Pipeline (ReAct -> Tools -> Report -> Evaluator)", "Generated report and scored >= 85.0/100 on 21-metric evaluation scorecard.")
    ]

    for cid, title, expected_tools, criteria in criteria_details:
        r_item = next((r for r in results if r["challenge_id"] == cid), {})
        status_str = "PASSED ✅" if r_item.get("passed") else "FAILED ❌"
        lines.append(f"### {cid.upper()}: {title}")
        lines.append(f"- **Expected Tool Sequence**: `{expected_tools}`")
        lines.append(f"- **Success Criteria**: {criteria}")
        lines.append(f"- **Outcome**: {status_str}")
        lines.append(f"- **Agent Final Output**: *\"{r_item.get('final_answer', 'N/A')}\"*")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by Autonomous Financial Research Agent Evaluation Suite (Phase 7).*")

    out_path = Path("RESULTS.md").resolve()
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nSuccessfully generated benchmark centerpiece documentation at '{out_path}'.")
    return str(out_path)


if __name__ == "__main__":
    run_all_challenges()
