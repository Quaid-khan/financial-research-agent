"""Scorecard Data Model and Formatters for Agent Evaluation Framework.

Provides JSON and Markdown summary report rendering for 20+ evaluation metrics across 7 categories.
"""

import json
import logging
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

from eval.metrics import MetricResult

logger = logging.getLogger("financial_agent.eval.scorecard")


def compute_grade(score: float) -> str:
    """Map numeric score (0-100) to institutional letter grade."""
    if score >= 95.0:
        return "A+"
    elif score >= 90.0:
        return "A"
    elif score >= 80.0:
        return "B"
    elif score >= 70.0:
        return "C"
    elif score >= 60.0:
        return "D"
    else:
        return "F"


class Scorecard(BaseModel):
    """Container for agent research performance evaluation across 20+ metrics."""
    overall_score: float = Field(description="Aggregate overall evaluation score (0.0 to 100.0).")
    grade: str = Field(description="Letter grade (A+, A, B, C, D, F).")
    category_scores: Dict[str, float] = Field(description="Average score per metric category.")
    metric_results: List[MetricResult] = Field(description="List of individual metric evaluation results.")
    recommendations: List[str] = Field(default_factory=list, description="Actionable improvement feedback recommendations.")

    def to_json(self, indent: int = 2) -> str:
        """Return formatted JSON representation of scorecard."""
        return json.dumps(self.model_dump(), indent=indent)

    def to_markdown(self) -> str:
        """Return publication-grade Markdown summary of scorecard results."""
        lines = [
            "# Autonomous Financial Agent Scorecard",
            "",
            f"**Overall Score**: `{self.overall_score:.2f} / 100.0` | **Grade**: `{self.grade}`",
            "---",
            "",
            "## Category Performance Summary",
            "| Category | Category Score | Performance Grade |",
            "| :--- | :--- | :--- |"
        ]

        for cat, score in self.category_scores.items():
            g = compute_grade(score)
            lines.append(f"| {cat} | {score:.2f} / 100.0 | {g} |")

        lines.append("")
        lines.append("## Detailed Metric Breakdown (21 Named Metrics)")
        lines.append("| Category | Metric Name | Score | What Good Looks Like |")
        lines.append("| :--- | :--- | :--- | :--- |")

        for m in self.metric_results:
            lines.append(f"| {m.category} | `{m.metric_name}` | {m.score:.2f} | {m.description} |")

        if self.recommendations:
            lines.append("")
            lines.append("## Actionable Improvement Recommendations")
            for r in self.recommendations:
                lines.append(f"- {r}")

        lines.append("")
        lines.append("---")
        lines.append("*Generated by Financial Agent Evaluation Suite (Phase 6).*")

        return "\n".join(lines)
